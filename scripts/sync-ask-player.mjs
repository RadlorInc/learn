#!/usr/bin/env node
// Copies the whiteboard player and its voice (Pocket TTS) from the askRadlor / Whiteboard AI app into Radlic, for
// Ask maths (docs/product/ask-maths.md). Run it again whenever that app's player or maths drawings change:
//   node scripts/sync-ask-player.mjs ../whiteboard-ai/app
// What it writes (committed, served as they are — no build step):
//   public/ask-player/  index.html (patched, below), bridge.js, recipes.js, answers.js, lib/wb-load.js, and only the
//                       drawing files a maths lesson loads (lib/wb-load.js's WB_CATS + WB_SUBJECT.maths): no realistic
//                       drawings (lib/sv, 91 MB) — the maths prompt may not use them (the server refuses sv/pin).
//   public/ask-tts/     the voice worker, its runtime and the six voices, with "/tts/" rewritten to "/ask-tts/".
// Patches, each checked (the script stops if a pattern is not found, so a changed upstream file cannot slip through):
//   - index.html's Google Fonts <link> → fonts.css here: Radlic's own Gaegu files under the names the player asks for
//     (Kalam, Caveat). A child's browser never asks Google for anything.
import fs from 'node:fs'
import path from 'node:path'
import { execFileSync } from 'node:child_process'

const src = path.resolve(process.argv[2] ?? '')
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..')
const P = path.join(src, 'public', 'player'), T = path.join(src, 'public', 'tts')
if (!fs.existsSync(path.join(P, 'index.html')) || !fs.existsSync(path.join(T, 'pocket-worker.js'))) {
  console.error(`usage: node scripts/sync-ask-player.mjs <path to the whiteboard-ai app checkout>\n  (no public/player or public/tts under ${src})`)
  process.exit(2)
}
const outP = path.join(root, 'public', 'ask-player'), outT = path.join(root, 'public', 'ask-tts')
fs.rmSync(outP, { recursive: true, force: true }); fs.rmSync(outT, { recursive: true, force: true })

const copy = (from, to) => { fs.mkdirSync(path.dirname(to), { recursive: true }); fs.copyFileSync(from, to) }
const patch = (s, from, to, what) => { if (!s.includes(from)) { console.error(`sync-ask-player: ${what} not found — upstream changed, check the patch`); process.exit(1) } return s.split(from).join(to) }

// ── the player ──
for (const f of ['bridge.js', 'recipes.js', 'answers.js', 'lib/wb-load.js']) copy(path.join(P, f), path.join(outP, f))
const loader = fs.readFileSync(path.join(P, 'lib', 'wb-load.js'), 'utf8')
const list = name => JSON.parse(loader.match(new RegExp(`window\\.${name} = (\\[[^\\]]*\\])`))[1])
const subjects = JSON.parse(loader.match(/window\.WB_SUBJECT = (\{[^;]*\});/)[1].replace(/(\w+):/g, '"$1":'))
if (!subjects.maths) { console.error('sync-ask-player: WB_SUBJECT has no maths entry — that app is older than the maths subject'); process.exit(1) }
const cats = [...list('WB_CATS'), ...subjects.maths]
for (const c of cats) copy(path.join(P, 'lib', 'wb', `${c}.js`), path.join(outP, 'lib', 'wb', `${c}.js`))

let html = fs.readFileSync(path.join(P, 'index.html'), 'utf8')
html = html.replace(/<link href="https:\/\/fonts\.googleapis\.com\/[^"]*" rel="stylesheet">/, m => m ? '<link href="fonts.css" rel="stylesheet">' : m)
if (/fonts\.googleapis|fonts\.gstatic/.test(html) || !html.includes('<link href="fonts.css" rel="stylesheet">')) {
  console.error('sync-ask-player: the Google Fonts link in index.html did not become fonts.css'); process.exit(1)
}
fs.writeFileSync(path.join(outP, 'index.html'), html)
const appFonts = fs.readFileSync(path.join(root, 'src', 'app', 'fonts.css'), 'utf8')
const gaegu = appFonts.match(/@font-face\{font-family:Gaegu;[^}]*\}/g) ?? []
if (!gaegu.length) { console.error('sync-ask-player: no Gaegu @font-face in src/app/fonts.css'); process.exit(1) }
fs.writeFileSync(path.join(outP, 'fonts.css'), `/* Generated by scripts/sync-ask-player.mjs: Radlic's self-hosted Gaegu (src/app/fonts.css, OFL 1.1) under the
   names the whiteboard player asks for, so it loads nothing from another site. */\n` +
  ['Kalam', 'Caveat'].map(n => gaegu.map(r => r.replace('font-family:Gaegu;', `font-family:${n};`)).join('\n')).join('\n') + '\n')

// ── the voice ──
const walk = d => fs.readdirSync(d, { withFileTypes: true }).flatMap(e => e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)])
for (const f of walk(T)) copy(f, path.join(outT, path.relative(T, f)))
const files = path.join(outT, 'pocket-files.mjs'), worker = path.join(outT, 'pocket-worker.js')
fs.writeFileSync(files, patch(fs.readFileSync(files, 'utf8'), 'url: "/tts/pocket-voices.bin"', 'url: "/ask-tts/pocket-voices.bin"', 'the voices URL'))
fs.writeFileSync(worker, patch(fs.readFileSync(worker, 'utf8'), '`/tts/kept/', '`/ask-tts/kept/', 'the kept-files cache key'))

let sha = 'unknown'
try { sha = execFileSync('git', ['-C', src, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim() } catch {}
const note = `Copied by scripts/sync-ask-player.mjs from RadlorInc/whiteboard-ai at ${sha}. Do not edit here: change it there and copy again.\n`
fs.writeFileSync(path.join(outP, 'SOURCE.txt'), note); fs.writeFileSync(path.join(outT, 'SOURCE.txt'), note)
console.log(`ask-player: ${cats.length} drawing files (${cats.join(' ')}); ask-tts: ${walk(outT).length} files; from ${sha}`)
