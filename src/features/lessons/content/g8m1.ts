const eq = (text: string, lines?: string[]): Picture => ({ kind: 'eq', text, lines })
const cards = (wrong: string, right: string): Picture => ({ kind: 'cards', wrong, right })
/** One tape row of factors, each 1 wide; the first `shade` cells are shaded. */
const row = (base: string, n: number, label?: string, shade = 0, brace?: string) =>
  ({ label, cells: Array.from({ length: n }, (_, i) => ({ w: 1, text: base, shade: i < shade })), brace })
const tape = (rows: ReturnType<typeof row>[], motion = false): Picture => ({ kind: 'tape', rows, motion })
const table = (head: string[], rows: string[][], extra: { mark?: [number, number][]; motion?: boolean; rowHead?: boolean } = {}): Picture =>
  ({ kind: 'table', head, rows, ...extra })
/** A square layer (h = 1) or a cube of unit cubes. */
const cubes = (l: number, h: number, motion = false): Picture => ({ kind: 'cubes', l, w: l, h, motion })
/** A number line from 0 with only its ends labelled and one marked point: a scratch line that names no root. */
const scratch = (at: number, max = 100): Picture =>
  ({ kind: 'numline', min: 0, max, ticks: max / 10, labels: 'ends', points: [{ at, label: String(at) }] })
/** 16 to 25, one tick per whole number, with the two squares and 20 labelled. */
const SQUARES_20 = (extra: Partial<Extract<Picture, { kind: 'numline' }>> = {}): Picture =>
  ({ kind: 'numline', min: 16, max: 25, ticks: 9, labels: ['16 = 4²', null, null, null, '20', null, null, null, null, '25 = 5²'], ...extra })

