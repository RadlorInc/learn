/** t5 teaching division: 5,184 ÷ 24. */
const eggs = (quotient?: string, work?: string[]): Picture => ({ kind: 'longdiv', divisor: '24', dividend: '5184', quotient, work })

/** t6: the price-for-one table. */
const PACK = ['Pack', 'Price', 'Price for one']
const packs = (rows: string[][], mark?: [number, number][], motion = false): Picture => ({ kind: 'table', head: PACK, rows, mark, motion })

