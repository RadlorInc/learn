/** Two labelled, unshaded bars: the question for a compare problem, never the answer. */
const pair = (a: [number, string], b: [number, string]): Picture =>
  ({ kind: 'bars', bars: [{ parts: a[0], shaded: 0, label: a[1] }, { parts: b[0], shaded: 0, label: b[1] }] })

/** n copies of one shaded piece out of `parts`. */
const copies = (n: number, parts: number, shaded = 1): Picture =>
  ({ kind: 'bars', bars: Array.from({ length: n }, () => ({ parts, shaded })) })

