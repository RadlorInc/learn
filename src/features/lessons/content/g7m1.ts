import type { Lesson, Picture } from '../script'

type TapeRow = Extract<Picture, { kind: 'tape' }>['rows'][number]
const tape = (rows: TapeRow[], motion = false): Picture => ({ kind: 'tape', rows, motion })
/** A table whose first cell of each row is its name. */
const table = (rows: string[][], head?: string[], mark?: [number, number][], motion = false): Picture =>
  ({ kind: 'table', head, rows, rowHead: true, mark, motion })
/** A straight line from (0, 0) through one labeled point. */
const graph = (x: number, y: number, motion = false): Picture =>
  ({ kind: 'coord', min: 0, max: 10, points: [{ x, y, label: `(${x}, ${y})` }], lines: [{ a: [0, 0], b: [x, y], extend: true }], motion })
/** `n` equal pieces of time on top; the amount done in the first piece below. `all` fills every piece. */
const perOne = (n: number, piece: string, first: string, amount: string, whole = '1 hour', timeLabel = 'Time', all?: string, brace = '?', motion = false): Picture =>
  tape([
    { label: timeLabel, cells: Array.from({ length: n }, (_, i) => ({ w: 1, text: piece, shade: i === 0 || !!all })), brace: whole },
    { label: amount, cells: Array.from({ length: n }, (_, i) => ({ w: 1, text: i === 0 ? first : all, shade: i === 0 || !!all })), brace },
  ], motion)
/** Before and after, drawn to scale; the change is the shaded piece. */
const change = (before: string, b: number, after: string, a: number, motion = false): Picture => a > b
  ? tape([{ label: 'Before', cells: [{ w: b, text: before }] }, { label: 'After', cells: [{ w: b, text: before }, { w: a - b, shade: true }], brace: after }], motion)
  : tape([{ label: 'Before', cells: [{ w: a }, { w: b - a, shade: true }], brace: before }, { label: 'After', cells: [{ w: a, text: after }] }], motion)
/** A price with percent pieces added on the end. */
const addOn = (price: string, extras: string[], brace = 'Total: ?', motion = false): Picture =>
  tape([{ cells: [{ w: 10, text: price }, ...extras.map(text => ({ w: 3, text, shade: true }))], brace }], motion)
/** A guess and the real amount, drawn to scale. */
const guess = (g: string, gw: number, r: string, rw: number): Picture =>
  tape([{ label: 'Guess', cells: [{ w: gw, text: g }] }, { label: 'Real', cells: [{ w: rw, text: r }] }])

