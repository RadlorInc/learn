'use client'
/**
 * English or Spanish for the PARENT dashboard (founder, 2026-09-22). A teacher's dashboard stays English: the page
 * passes 'en' for a teacher whatever this device has saved, and the teacher-only strings are not wrapped at all.
 *
 * The English text IS the key: `t('What {name} sees', { name })`. A key with no Spanish falls back to English, so
 * `src/__tests__/dashboardSpanish.test.ts` fails if a wrapped string has no entry here — without it a missing
 * translation would look exactly like a finished one to anyone who does not read Spanish.
 * Lessons, module and topic titles stay English (they are the lesson content, not the dashboard).
 *
 * ponytail: saved per DEVICE (founder's call — a parent on a new device picks it again). Move to `profiles` if asked.
 */
import { createContext, useContext, useSyncExternalStore } from 'react'

export type Lang = 'en' | 'es'
export type T = (s: string, v?: Record<string, string | number>) => string

const KEY = 'al-lang'
export function loadLang(): Lang {
  try { return localStorage.getItem(KEY) === 'es' ? 'es' : 'en' } catch { return 'en' }
}
export function saveLang(l: Lang): void {
  try { localStorage.setItem(KEY, l) } catch { /* private mode: the choice holds for this visit */ }
  window.dispatchEvent(new Event(KEY))
}

/** The saved choice, for pages outside the dashboard (sign-in, sign-up). The server renders English and the device's
 *  choice follows on the client, so a Spanish device never trips a hydration mismatch. */
export function useSavedLang(): Lang {
  return useSyncExternalStore(
    on => { window.addEventListener(KEY, on); window.addEventListener('storage', on); return () => { window.removeEventListener(KEY, on); window.removeEventListener('storage', on) } },
    loadLang, () => 'en')
}

// A key may carry a context after `|` when one English word needs two Spanish ones ('Done' the button, 'Done|lessons'
// the count); English shows the part before it.
export const makeT = (lang: Lang): T => (s, v) => {
  const base = s.split('|')[0]
  const out = lang === 'es' ? ES[s] ?? base : base
  return v ? out.replace(/\{(\w+)\}/g, (m, k: string) => (k in v ? String(v[k]) : m)) : out
}
export const en = makeT('en')

export const LangContext = createContext<Lang>('en')
export const useLang = () => useContext(LangContext)
export const useT = () => makeT(useLang())

